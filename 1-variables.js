// variables are used to store data values. In JavaScript, there are three ways to declare a variable: using var, let, and const.

// 1. var: The var keyword is used to declare a variable. It has function scope and can be re-declared and updated within its scope.
var name = "John";
console.log(name); // Output: John

// 2. let: The let keyword is used to declare a block-scoped variable. It can be updated but not re-declared within its scope.
let age = 30;
console.log(age); // Output: 30

// 3. const: The const keyword is used to declare a block-scoped variable that cannot be updated or re-declared. It must be initialized at the time of declaration.
const country = "USA";
console.log(country); // Output: USA


// var can be re-declared and re-assigned
// let can be reassigned but not re-declared
// const cannot be reassigned or re-declared





